"""SYNTHETIC demo data: made-up KOSPI- and KOSDAQ-like stocks, ETFs and indices, for trying krx-lean without
API keys and for tests. **None of it is real market data.**

``generate`` writes raw files in exactly the format the real downloads use (KRX daily trading
files, KRX index files, a data.go.kr dividend snapshot), so the normal ``build`` and
``lean-install`` turn them into LEAN data. Every company is named "SYNTHETIC DEMO …", codes
start with "D" (no real KRX code does), and ``SYNTHETIC-DEMO-DATA.txt`` marks the folders.

Prices follow a seeded random walk (the same every time): one market factor plus noise per
stock. The data includes a 5:1 split, a delisting, a listing during the period, a preferred
share, annual cash dividends and ETFs, so every part of the pipeline and the models is used.
"""

from __future__ import annotations

import datetime as dt
import math
import random
from pathlib import Path

from krx_lean.krx_api import day_path, write_day

MARKER = "SYNTHETIC-DEMO-DATA.txt"
MARKER_TEXT = """SYNTHETIC DEMO DATA - NOT REAL MARKET DATA

Every price, volume, index level and dividend in this folder was generated by
`krx_lean/demo.py` (a seeded random walk). The companies, codes (D00010, Q00010, ...) and
events do not exist. Use it to try krx-lean and klean without API keys; never draw
conclusions about the Korean market from it. Real data: docs/user/2-data.md.
"""
START, END = "20110103", "20260930"
SEED = 20261105

# (code, name suffix, board, start, end, base price, beta, listed shares)
SECURITIES = [
    ("D00010", "01", "KOSPI", None, None, 52_000, 1.1, 5_900_000_000),
    ("D00020", "02 (5:1 split 2018)", "KOSPI", None, None, 1_800_000, 1.2, 140_000_000),
    ("D00030", "03 (delisted 2019)", "KOSPI", None, "20190628", 24_000, 0.9, 680_000_000),
    ("D00040", "04 (listed 2015)", "KOSPI", "20150601", None, 31_000, 1.3, 410_000_000),
    ("D00015", "01 PREFERRED", "KOSPI", None, None, 43_000, 1.0, 820_000_000),
    *[(f"D{i:04d}0", f"{i:02d}", "KOSPI", None, None, 5_000 + 9_000 * i, 0.6 + 0.04 * i,
       60_000_000 + 25_000_000 * i) for i in range(5, 29)],
    ("E00010", "ETF KOSPI200 TRACKER", "ETF", None, None, 25_000, 1.0, 120_000_000),
    ("E00020", "ETF BOND", "ETF", None, None, 100_000, 0.05, 30_000_000),
    ("E00030", "ETF LEVERAGE", "ETF", None, None, 10_000, 2.0, 200_000_000),
]
# KOSDAQ-like stocks: generated in their own pass with their own random stream, so adding them
# didn't change the KOSPI and ETF series. (code, name suffix, base price, beta, listed shares)
KOSDAQ_SECURITIES = [(f"Q{i:04d}0", f"KOSDAQ {i:02d}", 3_000 + 7_000 * i, 1.1 + 0.1 * i, 20_000_000 + 9_000_000 * i)
                     for i in range(1, 7)]
SPLIT = ("D00020", "20180504", 5)            # code, first day at the new price, ratio
DIVIDEND_RATE = 0.015                        # yearly cash dividend, share of the price
MARKET_DRIFT = 0.04                          # yearly log trend of the market factor


def tick(price: float) -> int:
    """Round to the KRX tick table (2023) so prices look like exchange prices."""
    for limit, step in ((2_000, 1), (5_000, 5), (20_000, 10), (50_000, 50), (200_000, 100), (500_000, 500)):
        if price < limit:
            return max(step, int(round(price / step)) * step)
    return max(1_000, int(round(price / 1_000)) * 1_000)


def walk(rng: random.Random, n: int, sigma: float, total: float) -> list[float]:
    """Cumulative log path of ``n`` points with daily volatility ``sigma`` ending at ``total``."""
    steps = [rng.gauss(0.0, sigma) for _ in range(n - 1)]
    shift = (total - sum(steps)) / max(len(steps), 1)
    path = [0.0]
    for s in steps:
        path.append(path[-1] + s + shift)
    return path


def trading_days(start: str, end: str, holidays: set[str]) -> list[str]:
    d = dt.datetime.strptime(start, "%Y%m%d").date()
    stop = dt.datetime.strptime(end, "%Y%m%d").date()
    out = []
    while d <= stop:
        s = d.strftime("%Y%m%d")
        if d.weekday() < 5 and s not in holidays:
            out.append(s)
        d += dt.timedelta(days=1)
    return out


def generate(root: Path, holidays: set[str] | None = None, start: str = START, end: str = END,
             seed: int = SEED) -> dict:
    """Write synthetic raw files under ``root/raw``. ``holidays`` (yyyyMMdd) are left out of the
    calendar; klean passes LEAN's KRX holiday list so the demo calendar matches LEAN's."""
    rng = random.Random(seed)
    days = trading_days(start, end, holidays or set())
    # Random walks whose overall trend is pinned (a seed must not decide whether the demo market
    # booms): the market factor ends ~4%/year up (~17% volatility), each stock's own noise nets to 0.
    market = walk(rng, len(days), 0.011, MARKET_DRIFT * len(days) / 250)
    noise = {s[0]: walk(rng, len(days), 0.012, 0.0) for s in SECURITIES}

    prev_close: dict[str, int] = {}
    shares = {s[0]: s[7] for s in SECURITIES}
    split_code, split_day, ratio = SPLIT
    rows_by_day: dict[str, dict[str, list[dict]]] = {}
    for i, day in enumerate(days):
        for code, suffix, board, first, last, base, beta, _ in SECURITIES:
            if (first and day < first) or (last and day > last):
                continue
            level = base * math.exp(beta * market[i] + noise[code][i])
            if code == split_code and day >= split_day:
                level /= ratio
            close = tick(level)
            prev = prev_close.get(code)
            if prev is None:
                change, open_ = 0, close
            elif code == split_code and day == split_day:
                shares[code] *= ratio
                base_price = round(prev / ratio)          # KRX's base price: previous close / ratio
                change, open_ = close - base_price, tick(base_price)
            else:
                change, open_ = close - prev, tick(prev * math.exp(rng.gauss(0, 0.004)))
            high = tick(max(open_, close) * (1 + abs(rng.gauss(0, 0.008))))
            low = tick(min(open_, close) * (1 - abs(rng.gauss(0, 0.008))))
            volume = int(shares[code] * rng.uniform(0.0005, 0.004))
            rows_by_day.setdefault(day, {}).setdefault(board, []).append({
                "BAS_DD": day, "ISU_CD": code, "ISU_NM": f"SYNTHETIC DEMO {suffix}", "MKT_NM": board,
                "TDD_OPNPRC": str(open_), "TDD_HGPRC": str(max(high, open_, close)),
                "TDD_LWPRC": str(min(low, open_, close)), "TDD_CLSPRC": str(close),
                "CMPPREVDD_PRC": str(change), "ACC_TRDVOL": str(volume), "ACC_TRDVAL": str(volume * close),
                "MKTCAP": str(close * shares[code]), "LIST_SHRS": str(shares[code])})
            prev_close[code] = close

    for day, boards in rows_by_day.items():
        for board in ("KOSPI", "ETF"):
            write_day(day_path(root, board, day), boards.get(board, []))

    # Indices: KOSPI and KOSPI 200 follow the market factor (the names KRX uses, so build
    # writes them as kospi / kospi200).
    for i, day in enumerate(days):
        rows = []
        for name, base, scale in (("코스피", 2_000.0, 1.0), ("코스피 200", 260.0, 1.05)):
            c = base * math.exp(scale * market[i])
            o = c * math.exp(rng.gauss(0, 0.003))
            rows.append({"BAS_DD": day, "IDX_CLSS": "KOSPI", "IDX_NM": name, "CLSPRC_IDX": f"{c:.2f}",
                         "CMPPREVDD_IDX": "0", "FLUC_RT": "0", "OPNPRC_IDX": f"{o:.2f}",
                         "HGPRC_IDX": f"{max(o, c) * 1.004:.2f}", "LWPRC_IDX": f"{min(o, c) * 0.996:.2f}",
                         "ACC_TRDVOL": "0", "ACC_TRDVAL": "0", "MKTCAP": "0"})
        write_day(day_path(root, "KOSPI", day, subdir="krx_index"), rows)

    # Dividends (data.go.kr format): one cash dividend a year for common stocks, record date =
    # the last trading day of the year.
    year_end = {}
    for day in days:
        year_end[day[:4]] = day
    closes_at: dict[tuple[str, str], int] = {}
    for day in year_end.values():
        for row in rows_by_day[day].get("KOSPI", []):
            closes_at[(row["ISU_CD"], day)] = int(row["TDD_CLSPRC"])
    dividends = []
    for (code, day), close in sorted(closes_at.items()):
        if code.endswith("0") and day < days[-1]:
            dividends.append({
                "basDt": day, "crno": "", "isinCd": f"KR7{code}000", "isinCdNm": "SYNTHETIC DEMO",
                "scrsItmsKcdNm": "보통주", "stckStacMd": "12", "dvdnBasDt": day, "cashDvdnPayDt": "",
                "stckHndvDt": "", "stckDvdnRcd": "02", "stckDvdnRcdNm": "현금배당",
                "stckGenrDvdnAmt": str(int(close * DIVIDEND_RATE)), "stckGrdnDvdnAmt": "",
                "stckGenrCashDvdnRt": "", "stckGenrDvdnRt": "", "stckParPrc": "100"})
    write_day(root / "raw" / "dividends" / f"{days[-1]}.csv.gz", dividends)

    # KOSDAQ: its own random stream (see KOSDAQ_SECURITIES), the same market factor, more noise.
    rng_q = random.Random(seed + 1)
    noise_q = {s[0]: walk(rng_q, len(days), 0.018, 0.0) for s in KOSDAQ_SECURITIES}
    prev_q: dict[str, int] = {}
    for i, day in enumerate(days):
        rows = []
        for code, suffix, base, beta, listed in KOSDAQ_SECURITIES:
            close = tick(base * math.exp(beta * market[i] + noise_q[code][i]))
            prev = prev_q.get(code, close)
            open_ = tick(prev * math.exp(rng_q.gauss(0, 0.005)))
            high = max(tick(max(open_, close) * (1 + abs(rng_q.gauss(0, 0.01)))), open_, close)
            low = min(tick(min(open_, close) * (1 - abs(rng_q.gauss(0, 0.01)))), open_, close)
            volume = int(listed * rng_q.uniform(0.001, 0.008))
            rows.append({"BAS_DD": day, "ISU_CD": code, "ISU_NM": f"SYNTHETIC DEMO {suffix}", "MKT_NM": "KOSDAQ",
                         "TDD_OPNPRC": str(open_), "TDD_HGPRC": str(high), "TDD_LWPRC": str(low),
                         "TDD_CLSPRC": str(close), "CMPPREVDD_PRC": str(close - prev), "ACC_TRDVOL": str(volume),
                         "ACC_TRDVAL": str(volume * close), "MKTCAP": str(close * listed), "LIST_SHRS": str(listed)})
            prev_q[code] = close
        write_day(day_path(root, "KOSDAQ", day), rows)
        index_rows = []
        for name, base, scale in (("코스닥", 500.0, 1.25), ("코스닥 150", 800.0, 1.3)):
            c = base * math.exp(scale * market[i])
            index_rows.append({"BAS_DD": day, "IDX_CLSS": "KOSDAQ", "IDX_NM": name, "CLSPRC_IDX": f"{c:.2f}",
                               "CMPPREVDD_IDX": "0", "FLUC_RT": "0", "OPNPRC_IDX": f"{c:.2f}",
                               "HGPRC_IDX": f"{c * 1.004:.2f}", "LWPRC_IDX": f"{c * 0.996:.2f}",
                               "ACC_TRDVOL": "0", "ACC_TRDVAL": "0", "MKTCAP": "0"})
        write_day(day_path(root, "KOSDAQ", day, subdir="krx_index"), index_rows)

    root.mkdir(parents=True, exist_ok=True)
    (root / MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    return {"days": len(days), "first": days[0], "last": days[-1],
            "securities": len(SECURITIES) + len(KOSDAQ_SECURITIES), "dividends": len(dividends)}


def is_demo(folder: Path) -> bool:
    """True if ``folder`` (a pipeline root or a LEAN data folder) holds synthetic demo data."""
    return any((folder / sub / MARKER).exists() for sub in ("", "equity/krx", "lean/equity/krx"))
