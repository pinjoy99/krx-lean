"""`klean research`: Jupyter notebooks with LEAN's QuantBook on the workspace's data, like
`lean research` but without Docker.

LEAN's build already contains the research parts (``QuantConnect.Research.dll`` and
``start.py`` in ``Launcher/bin/Release``). ``start.py`` loads .NET into Python with clr-loader
and pythonnet and starts LEAN's handlers from ``./config.json``. klean therefore:

1. installs JupyterLab, ipykernel and clr-loader (the versions of LEAN's Docker image) into the
   workspace's Python 3.11 environment, once;
2. writes ``<workspace>/.klean/research/config.json`` (data folder = the workspace's ``data/``)
   and an IPython startup file that runs LEAN's own ``start.py`` from that folder, so every
   notebook kernel starts with LEAN loaded (``QuantBook``, ``Resolution``, ``Market``, ...);
3. starts JupyterLab on 127.0.0.1 in the project folder, so notebooks import the project's
   modules (``krx_models``) the same way the algorithm does.

The project's notebook is ``research.ipynb`` (the LEAN CLI's name); klean writes a starter one
if there is none. ``--execute`` runs a notebook without a browser (for scripts and tests).
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import socket
import subprocess
import threading
from pathlib import Path

from klean import projects, results
from klean.backtest import python_env
from klean.workspace import KleanError, Workspace, dotnet, git_commit, run, venv_python

# JupyterLab and clr-loader as in LEAN's DockerfileLeanFoundation / DockerfileJupyter at the tested
# commit; matplotlib as for `klean report`.
RESEARCH_PACKAGES = ["jupyterlab==4.5.1", "ipykernel", "clr-loader==0.2.9", "matplotlib==3.8.4"]
NOTEBOOK = "research.ipynb"
STARTUP = "00-klean-lean.py"


def research_dir(ws: Workspace) -> Path:
    return ws.root / ".klean" / "research"


def ensure_packages(ws: Workspace, log=print) -> None:
    py = str(venv_python(ws.python_venv))
    check = "import jupyterlab, ipykernel, nbconvert, clr_loader, matplotlib"
    if subprocess.run([py, "-c", check], capture_output=True).returncode:
        log(f"klean: installing {' '.join(RESEARCH_PACKAGES)} into {ws.python_venv} (once, a few minutes)")
        run([py, "-m", "pip", "install", "-q", *RESEARCH_PACKAGES], env=python_env(ws))


def prepare(ws: Workspace) -> dict[str, str]:
    """Write the LEAN config and the IPython startup file; return the environment for Jupyter."""
    env = python_env(ws)                    # also checks that the workspace has a Python env
    start = ws.launcher_dir / "start.py"
    if not (start.exists() and (ws.launcher_dir / "QuantConnect.Research.dll").exists()):
        raise KleanError(f"LEAN's research files aren't in {ws.launcher_dir}: rebuild LEAN "
                         "(`klean update lean`)")
    folder = research_dir(ws)
    startup = folder / "ipython" / "profile_default" / "startup"
    startup.mkdir(parents=True, exist_ok=True)
    # krx_models.py for projects without their own copy (C# projects); the project's copy comes first
    (folder / "lib").mkdir(exist_ok=True)
    shutil.copy(projects.PY_MODELS, folder / "lib" / "krx_models.py")
    (folder / "config.json").write_text(json.dumps({
        "data-folder": f"{ws.data}/",
        "composer-dll-directory": f"{ws.launcher_dir}/",
        "algorithm-language": "Python",
        "messaging-handler": "QuantConnect.Messaging.Messaging",
        "job-queue-handler": "QuantConnect.Queues.JobQueue",
        "api-handler": "QuantConnect.Api.Api",
        # LEAN's trace lines go to <workspace>/.klean/research/log.txt instead of every cell's output
        "log-handler": "QuantConnect.Logging.FileLogHandler",
        "object-store-root": f"{ws.root / 'storage'}",      # one object store per workspace, like the LEAN CLI
        **ws.lean_config}, indent=2) + "\n", encoding="utf-8")
    banner = f"*** {results.DEMO_BANNER} ***" if results.is_demo_data(ws) else ""
    (startup / STARTUP).write_text(STARTUP_TEMPLATE.format(
        bin=str(ws.launcher_dir), start=str(start), config_dir=str(folder), lib=str(folder / "lib"),
        config=str(folder / "config.json"),
        data=str(ws.data),
        lean=(git_commit(Path(ws.lean_root)) or "?")[:7], banner=banner), encoding="utf-8")
    return {**env, "DOTNET_ROOT": str(Path(dotnet()).resolve().parent),
            "IPYTHONDIR": str(folder / "ipython"), "PYTHONNOUSERSITE": "1"}


STARTUP_TEMPLATE = '''# klean research: loads LEAN into every notebook kernel (generated by klean; edits are overwritten).
import os as _os
import sys as _sys

_sys.path.insert(1, {bin!r})
_sys.path.append({lib!r})           # krx_models.py if the project has none
_here = _os.getcwd()
_os.chdir({config_dir!r})          # LEAN reads ./config.json: the workspace's data folder
try:
    _g = globals()
    _g["__file__"] = {start!r}
    exec(compile(open({start!r}, encoding="utf-8").read(), {start!r}, "exec"), _g)
finally:
    _os.chdir(_here)
    globals().pop("__file__", None)
# QuantBook() calls Config.Reset(), which re-reads config.json from the current folder (the project):
# point LEAN at klean's file by its absolute path instead.
Config.SetConfigurationFile({config!r})
Config.Reset()
if {banner!r}:
    print({banner!r})
print("klean research: LEAN {lean} loaded; QuantBook() reads {data}")
'''


def notebook_template(demo: bool) -> dict:
    code = "D00010" if demo else "005930"
    name = "the synthetic demo stock D00010" if demo else "Samsung Electronics (005930)"
    cells = [
        ("markdown", "# Research\n\n"
         + ("**SYNTHETIC DEMO DATA: made-up prices, not real market data.**\n\n" if demo else "")
         + "LEAN is already loaded in this notebook (by `klean research`): `QuantBook` gives history from "
           "the workspace's KRX data, and `krx_models.py` from this project is importable.\n\n"
           "Note: `from AlgorithmImports import *` (done for you) replaces Python's `time` module with "
           "`datetime.time`; use `import time as time_module` if you need it."),
        ("code", "qb = QuantBook()\n"
                 "qb.set_time_zone(\"Asia/Seoul\")\n"
                 "from krx_models import KrxBoards, load_index\n"
                 "boards = KrxBoards.load()\n"
                 "print(len(boards), \"securities\")"),
        ("markdown", f"## Daily history of {name}\n\nPrices are adjusted for splits and dividends "
                     "(LEAN's default); add `data_normalization_mode=DataNormalizationMode.RAW` for exchange prices."),
        ("code", f"symbol = qb.add_equity(\"{code}\", Resolution.DAILY, Market.KRX).symbol\n"
                 "history = qb.history(symbol, datetime(2020, 1, 1), datetime(2025, 12, 31), Resolution.DAILY)\n"
                 "close = history.loc[symbol][\"close\"]\n"
                 "close.tail()"),
        ("code", "sma = qb.indicator(SimpleMovingAverage(60), symbol, datetime(2020, 1, 1), datetime(2025, 12, 31),\n"
                 "                    Resolution.DAILY)\n"
                 "ax = close.plot(figsize=(10, 4), title=\"close and 60-day average\", label=\"close\")\n"
                 "sma[\"current\"].plot(ax=ax, label=\"60-day average\")\n"
                 "ax.legend();"),
        ("markdown", "## Against the KOSPI 200\n\nIndex levels come from `data/index/krx/daily/kospi200.zip` "
                     "(`load_index` in `krx_models.py`)."),
        ("code", "import pandas as pd\n"
                 "dates, levels = load_index(\"kospi200\")\n"
                 "kospi200 = pd.Series(levels, index=pd.to_datetime(dates))\n"
                 "both = pd.DataFrame({\"stock\": close.groupby(close.index.date).last(), \"KOSPI 200\": kospi200}).dropna()\n"
                 "(both / both.iloc[0]).plot(figsize=(10, 4), title=\"growth of 1 won\");"),
    ]
    return {"cells": [{"cell_type": t, "id": f"klean-{i}", "metadata": {}, "source": s,
                       **({"execution_count": None, "outputs": []} if t == "code" else {})}
                      for i, (t, s) in enumerate(cells, 1)],
            "metadata": {"kernelspec": {"display_name": "Python 3 (LEAN, klean)", "language": "python",
                                        "name": "python3"},
                         "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 5}


def ensure_notebook(ws: Workspace, project: Path, name: str = NOTEBOOK) -> Path:
    nb = project / name
    if not nb.exists():
        nb.write_text(json.dumps(notebook_template(results.is_demo_data(ws)), indent=1) + "\n", encoding="utf-8")
    return nb


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def start(ws: Workspace, project: Path, port: int = 0, log=print, output=None) -> tuple[subprocess.Popen, str]:
    """Start JupyterLab for the project and return (process, URL with its token)."""
    ensure_packages(ws, log)
    env = prepare(ws)
    nb = ensure_notebook(ws, project)
    port = port or free_port()
    token = secrets.token_urlsafe(24)
    url = f"http://127.0.0.1:{port}/lab/tree/{nb.name}?token={token}"
    py = str(venv_python(ws.python_venv))
    cmd = [py, "-m", "jupyter", "lab", "--no-browser", "--ip=127.0.0.1", f"--port={port}",
           f"--ServerApp.root_dir={project}", f"--IdentityProvider.token={token}",
           "--ServerApp.port_retries=0",
           # no "news" / "new version" pop-ups (and no calls to jupyter.org): a local tool
           "--LabApp.news_url=None", "--LabApp.check_for_updates_class=jupyterlab.NeverCheckForUpdate"]
    if hasattr(os, "geteuid") and os.geteuid() == 0:     # containers, some WSL setups
        cmd.append("--allow-root")
    return subprocess.Popen(cmd, cwd=project, env={**os.environ, **env}, stdout=output, stderr=output), url


def launch(ws: Workspace, project: Path, port: int = 0, open_browser: bool = True, log=print) -> int:
    proc, url = start(ws, project, port, log)
    if results.is_demo_data(ws):
        log(f"*** {results.DEMO_BANNER} ***")
    log(f"klean research: JupyterLab for {project.name}\n  {url}\n(Ctrl+C to stop)")
    if open_browser:
        from klean.gui import open_page
        threading.Timer(3.0, lambda: open_page(url)).start()
    try:
        return proc.wait()
    except KeyboardInterrupt:
        proc.terminate()
        proc.wait()
        return 0


def execute(ws: Workspace, project: Path, notebook: str = NOTEBOOK, timeout: int = 600, log=print) -> Path:
    """Run a notebook without a browser; the executed copy is written next to it."""
    ensure_packages(ws, log)
    env = prepare(ws)
    nb = project / notebook if not Path(notebook).is_absolute() else Path(notebook)
    if notebook == NOTEBOOK:
        ensure_notebook(ws, project)
    if not nb.exists():
        raise KleanError(f"{nb} not found")
    out = nb.with_name(nb.stem + ".executed.ipynb")
    py = str(venv_python(ws.python_venv))
    cmd = [py, "-m", "jupyter", "nbconvert", "--to", "notebook", "--execute", str(nb), "--output", out.name,
           f"--ExecutePreprocessor.timeout={timeout}"]
    log(f"klean research: running {nb.name} -> {out.name}")
    r = subprocess.run(cmd, cwd=project, env={**os.environ, **env}, capture_output=True, text=True)
    if r.returncode:
        raise KleanError(f"the notebook failed:\n{(r.stderr or r.stdout)[-3000:]}")
    return out
